def get_icon(name: str, color: str = "#FFFFFF", size: int = 24) -> QIcon:
    """Render an SVG string into a tinted QIcon."""
    svg_str = LUCIDE_SVGS.get(name)
    if not svg_str:
        return QIcon()
        
    # Replace currentColor with our target color
    svg_str = svg_str.replace('currentColor', color)
    
    renderer = QSvgRenderer(QByteArray(svg_str.encode('utf-8')))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()
    
    return QIcon(pixmap)

def get_pixmap(name: str, color: str = "#FFFFFF", size: int = 24) -> QPixmap:
    return get_icon(name, color, size).pixmap(size, size)
